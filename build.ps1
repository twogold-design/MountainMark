param([string]$Godot = 'D:\tools\Godot-4.7.2\Godot_v4.7.2-stable_win64_console.exe')
$ErrorActionPreference = 'Stop'
$sourceRoot = $PSScriptRoot
$runtimeRoot = Join-Path (Split-Path -Parent $sourceRoot) 'MountainMark_web_source\.runtime'
$env:APPDATA = Join-Path $runtimeRoot 'AppData'
$env:LOCALAPPDATA = Join-Path $runtimeRoot 'LocalAppData'
$env:TEMP = Join-Path $runtimeRoot 'Temp'
$env:TMP = $env:TEMP
# Build a fresh copy so imports, caches and logs do not enter the competition folder.
$projectRoot = Join-Path $runtimeRoot ('build-project-' + [DateTime]::UtcNow.ToString('yyyyMMdd-HHmmss-fff'))
New-Item -ItemType Directory -Force -Path $projectRoot,$env:APPDATA,$env:LOCALAPPDATA,$env:TEMP | Out-Null
foreach ($name in @('assets','scenes','scripts','project.godot','export_presets.cfg','web_shell.html')) {
    Copy-Item -LiteralPath (Join-Path $sourceRoot $name) -Destination (Join-Path $projectRoot $name) -Recurse
}
& $Godot --headless --path $projectRoot --editor --import --quit --log-file (Join-Path $runtimeRoot 'web-import.log')
if ($LASTEXITCODE -ne 0) { throw 'Web project import failed.' }
& $Godot --headless --path $projectRoot --export-release 'Web' (Join-Path $sourceRoot 'index.html') --log-file (Join-Path $runtimeRoot 'web-export.log')
if ($LASTEXITCODE -ne 0) { throw 'Web export failed.' }
# Local file pages cannot fetch WASM/PCK. Classic scripts provide the same bytes
# without a server; HTTPS pages never load this additional bundle.
$bundlePath = Join-Path $sourceRoot 'index.offline.data.js'
$writer = [System.IO.StreamWriter]::new($bundlePath, $false, [System.Text.UTF8Encoding]::new($false))
try {
    $writer.WriteLine('// Generated by build.ps1 from the current web export. Do not edit.')
    $writer.WriteLine('window.MountainMarkLocalFiles={')
    $resources = [ordered]@{'index.wasm'='application/wasm'; 'index.pck'='application/octet-stream'; 'index.audio.worklet.js'='text/javascript'; 'index.audio.position.worklet.js'='text/javascript'}
    foreach ($name in $resources.Keys) {
        $bytes = [System.IO.File]::ReadAllBytes((Join-Path $sourceRoot $name))
        $writer.Write(('"{0}":{{"type":"{1}","size":{2},"base64":[' -f $name, $resources[$name], $bytes.Length))
        $chunkSize = 786432
        for ($offset = 0; $offset -lt $bytes.Length; $offset += $chunkSize) {
            if ($offset -gt 0) { $writer.Write(',') }
            $writer.Write('"')
            $writer.Write([Convert]::ToBase64String($bytes, $offset, [Math]::Min($chunkSize, $bytes.Length - $offset)))
            $writer.Write('"')
        }
        $writer.WriteLine(']},')
    }
    $writer.WriteLine('};')
} finally { $writer.Dispose() }
$total = (Get-ChildItem -LiteralPath $sourceRoot -File -Recurse | Measure-Object Length -Sum).Sum
if ($total -gt 200000000) { throw 'Complete folder exceeds the 200 MB competition limit.' }
Write-Output ('Complete web project ready: {0} ({1:N2} MB including editable source; no archive created)' -f $sourceRoot, ($total / 1000000))
